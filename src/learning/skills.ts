/** نقشه شناسه مهارت به تعریف */
export const SKILL_BY_ID: ReadonlyMap<string, SkillDefinition> = new Map(
  SKILLS.map((s) => [s.id, s])
);

/** مهارت‌های یک درس */
export function skillForLesson(lessonId: string): SkillDefinition | undefined {
  return SKILLS.find((s) => s.lessonId === lessonId);
}

/** مهارت‌های پیش‌نیاز یک مهارت (به‌صورت بازگشتی تا عمق معین برای تشخیص شکاف ریشه‌ای) */
export function prerequisiteChain(skillId: string, maxDepth = 3): string[] {
  const chain: string[] = [];
  const visited = new Set<string>([skillId]);
  const walk = (id: string, depth: number) => {
    if (depth > maxDepth) return;
    const skill = SKILL_BY_ID.get(id);
    for (const p of skill?.prerequisites ?? []) {
      if (!visited.has(p)) {
        visited.add(p);
        chain.push(p);
        walk(p, depth + 1);
      }
    }
  };
  walk(skillId, 1);
  return chain;
}
